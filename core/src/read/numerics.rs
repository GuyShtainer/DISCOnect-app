//! The two statistics Python's `statistics` module gives `data.facts`, bit for bit.
//!
//! * [`fsum`] is `math.fsum`: Shewchuk's exact summation with CPython's final half-even fix-up. It is
//!   what `statistics.fmean` uses (`fsum(data) / n`), and it is **not** the Neumaier loop of the
//!   builtin `sum` ([`crate::writer::py_sum`]).
//! * [`stdev`] is `statistics.stdev`: the variance is computed exactly as a rational from the exact
//!   values of the floats (`Fraction` arithmetic in Python), then its square root is rounded once,
//!   correctly (`_float_sqrt_of_frac`: round-to-odd integer square root, then an exactly rounded
//!   integer division). The exact rational lives here in a minimal unsigned big integer.
//!
//! A non-finite input, an intermediate overflow in `fsum`, and a result too large for a float are
//! the cases where Python raises; they are `None` here and the caller reports its own failure. The
//! differential fixture `tests/fixtures/py_numerics_read.json` (generated by
//! `hearthbeat/tests/gen_facts_numerics.py` with CPython 3.14) pins every bit.

use std::cmp::Ordering;

/// `math.fsum(values)`, or `None` when Python raises (a non-finite input or an intermediate overflow).
pub fn fsum(values: &[f64]) -> Option<f64> {
    let mut partials: Vec<f64> = Vec::new();
    for &value in values {
        if !value.is_finite() {
            return None;
        }
        let mut x = value;
        let mut kept: Vec<f64> = Vec::with_capacity(partials.len() + 1);
        for &partial in &partials {
            let mut y = partial;
            if x.abs() < y.abs() {
                std::mem::swap(&mut x, &mut y);
            }
            let hi = x + y;
            let yr = hi - x;
            let lo = y - yr;
            if lo != 0.0 {
                kept.push(lo);
            }
            x = hi;
        }
        if x != 0.0 {
            if !x.is_finite() {
                return None; // "intermediate overflow in fsum"
            }
            kept.push(x);
        }
        partials = kept;
    }
    let mut remaining = partials.len();
    let Some(mut hi) = remaining
        .checked_sub(1)
        .and_then(|top| partials.get(top).copied())
    else {
        return Some(0.0);
    };
    remaining -= 1;
    let mut lo = 0.0_f64;
    // Sum the partials from the top, stopping when the sum becomes inexact.
    while remaining > 0 {
        let x = hi;
        remaining -= 1;
        let y = partials.get(remaining).copied().unwrap_or(0.0);
        hi = x + y;
        let yr = hi - x;
        lo = y - yr;
        if lo != 0.0 {
            break;
        }
    }
    // Make half-even rounding work across multiple partials.
    if remaining > 0
        && let Some(&next) = partials.get(remaining - 1)
        && ((lo < 0.0 && next < 0.0) || (lo > 0.0 && next > 0.0))
    {
        let y = lo * 2.0;
        let x = hi + y;
        let yr = x - hi;
        if y == yr {
            hi = x;
        }
    }
    Some(hi)
}

/// `statistics.fmean(values)`: `fsum(values) / len(values)`. `None` for an empty list or when
/// [`fsum`] is `None`.
pub fn fmean(values: &[f64]) -> Option<f64> {
    if values.is_empty() {
        return None;
    }
    Some(fsum(values)? / values.len() as f64)
}

/// `statistics.stdev(values)` for floats: the correctly rounded square root of the exact sample
/// variance. `None` for fewer than two values, a non-finite value, or a result Python cannot make a
/// float of.
pub fn stdev(values: &[f64]) -> Option<f64> {
    let count = u64::try_from(values.len())
        .ok()
        .filter(|n| (2..=u64::from(u32::MAX)).contains(n))?;
    let mut parts = Vec::with_capacity(values.len());
    for &value in values {
        parts.push(Decomposed::of(value)?);
    }
    // Every value is a integer times 2^scale, scale the smallest exponent among the nonzero ones.
    let Some(scale) = parts.iter().filter(|p| p.mant != 0).map(|p| p.exp).min() else {
        return Some(0.0); // all zeros
    };
    let mut positive = Big::zero();
    let mut negative = Big::zero();
    let mut sum_squares = Big::zero();
    for part in &parts {
        if part.mant == 0 {
            continue;
        }
        let scaled = Big::from_u64(part.mant).shl(u64::try_from(part.exp - scale).ok()?);
        sum_squares = sum_squares.add(&scaled.mul(&scaled));
        if part.negative {
            negative = negative.add(&scaled);
        } else {
            positive = positive.add(&scaled);
        }
    }
    let total = if positive.cmp(&negative) == Ordering::Less {
        negative.sub(&positive)
    } else {
        positive.sub(&negative)
    };
    // (n * sum(x^2) - sum(x)^2) / (n * (n - 1)), all times 2^(2 * scale): the sample variance.
    let numerator = sum_squares.mul_u64(count).sub(&total.mul(&total));
    if numerator.is_zero() {
        return Some(0.0);
    }
    let result = sqrt_of_fraction(&numerator, count * (count - 1), i64::from(scale))?;
    result.is_finite().then_some(result)
}

/// A finite float as `(-1)^negative * mant * 2^exp`.
struct Decomposed {
    negative: bool,
    mant: u64,
    exp: i32,
}

impl Decomposed {
    fn of(value: f64) -> Option<Decomposed> {
        if !value.is_finite() {
            return None;
        }
        let bits = value.to_bits();
        let field = ((bits >> 52) & 0x7ff) as i32;
        let fraction = bits & ((1 << 52) - 1);
        let (mant, exp) = if field == 0 {
            (fraction, -1074)
        } else {
            (fraction | (1 << 52), field - 1075)
        };
        Some(Decomposed {
            negative: bits >> 63 == 1,
            mant,
            exp,
        })
    }
}

/// `sqrt(numerator / denominator * 4^scale)` rounded once to the nearest float (ties to even), by
/// CPython's recipe: the integer square root of the quotient, scaled to about 55 bits and rounded to
/// odd, then an exactly rounded conversion. `None` when the quotient does not fit the working width.
fn sqrt_of_fraction(numerator: &Big, denominator: u64, scale: i64) -> Option<f64> {
    /// `2 * float.mant_dig + 3`, as in `statistics._sqrt_bit_width`.
    const SQRT_BIT_WIDTH: i64 = 109;
    let numerator_bits = i64::try_from(numerator.bit_len()).ok()?;
    let denominator_bits = i64::from(64 - denominator.leading_zeros());
    let q = (numerator_bits - denominator_bits - SQRT_BIT_WIDTH).div_euclid(2);
    // quotient = floor(numerator' / denominator') with the scaling by 4^q applied to one side
    let (quotient, exact_division) = if q >= 0 {
        let shift = u64::try_from(2 * q).ok()?;
        let (whole, remainder) = numerator.divrem_u64(denominator);
        let exact = remainder == 0 && whole.low_bits_zero(shift);
        (whole.shr(shift), exact)
    } else {
        let (whole, remainder) = numerator
            .shl(u64::try_from(-2 * q).ok()?)
            .divrem_u64(denominator);
        (whole, remainder == 0)
    };
    let quotient = quotient.to_u128()?;
    let root = isqrt(quotient);
    let inexact = !(exact_division && root.checked_mul(root) == Some(quotient));
    let odd = root | u128::from(inexact);
    Some(ldexp_rounded(odd, q + scale))
}

/// `math.isqrt` for a `u128`.
fn isqrt(n: u128) -> u128 {
    if n < 2 {
        return n;
    }
    let mut x = (n as f64).sqrt() as u128;
    while x.checked_mul(x).is_none_or(|square| square > n) {
        x -= 1;
    }
    while (x + 1).checked_mul(x + 1).is_some_and(|square| square <= n) {
        x += 1;
    }
    x
}

/// `mant * 2^exp` rounded once to the nearest float, ties to even, subnormals included (the
/// correctly rounded integer true division Python performs).
fn ldexp_rounded(mant: u128, exp: i64) -> f64 {
    if mant == 0 {
        return 0.0;
    }
    let bits = i64::from(128 - mant.leading_zeros());
    let top = bits - 1 + exp; // exponent of the leading bit
    let quantum = (top - 52).max(-1074); // the exponent of one unit in the last place
    let drop = quantum - exp; // bits of `mant` below that unit
    let units = if drop <= 0 {
        mant << u32::try_from(-drop).unwrap_or(0) // at most 53 significant bits: exact
    } else if drop > 127 {
        0 // below half of the smallest unit
    } else {
        let drop = drop as u32;
        let kept = mant >> drop;
        let rest = mant & ((1u128 << drop) - 1);
        let half = 1u128 << (drop - 1);
        if rest > half || (rest == half && kept & 1 == 1) {
            kept + 1
        } else {
            kept
        }
    };
    if quantum > 971 {
        return f64::INFINITY;
    }
    let unit = if quantum >= -1022 {
        f64::from_bits(((quantum + 1023) as u64) << 52)
    } else {
        f64::from_bits(1u64 << (quantum + 1074))
    };
    units as f64 * unit
}

/// A minimal unsigned big integer: little-endian 64-bit limbs without trailing zero limbs.
#[derive(Clone, Debug, PartialEq, Eq)]
struct Big(Vec<u64>);

impl Big {
    fn zero() -> Big {
        Big(Vec::new())
    }

    fn from_u64(value: u64) -> Big {
        if value == 0 {
            Big::zero()
        } else {
            Big(vec![value])
        }
    }

    fn trim(mut self) -> Big {
        while self.0.last() == Some(&0) {
            self.0.pop();
        }
        self
    }

    fn is_zero(&self) -> bool {
        self.0.is_empty()
    }

    fn bit_len(&self) -> u64 {
        match self.0.last() {
            None => 0,
            Some(top) => (self.0.len() as u64 - 1) * 64 + u64::from(64 - top.leading_zeros()),
        }
    }

    fn shl(&self, bits: u64) -> Big {
        if self.is_zero() {
            return Big::zero();
        }
        let limbs = (bits / 64) as usize;
        let inner = (bits % 64) as u32;
        let mut out = vec![0u64; limbs];
        let mut carry = 0u64;
        for &limb in &self.0 {
            if inner == 0 {
                out.push(limb);
            } else {
                out.push((limb << inner) | carry);
                carry = limb >> (64 - inner);
            }
        }
        if carry != 0 {
            out.push(carry);
        }
        Big(out).trim()
    }

    fn shr(&self, bits: u64) -> Big {
        let limbs = (bits / 64) as usize;
        let inner = (bits % 64) as u32;
        let Some(rest) = self.0.get(limbs..) else {
            return Big::zero();
        };
        let mut out = Vec::with_capacity(rest.len());
        for (index, &limb) in rest.iter().enumerate() {
            if inner == 0 {
                out.push(limb);
            } else {
                let above = rest.get(index + 1).copied().unwrap_or(0);
                out.push((limb >> inner) | (above << (64 - inner)));
            }
        }
        Big(out).trim()
    }

    /// True when the lowest `bits` bits are all zero.
    fn low_bits_zero(&self, bits: u64) -> bool {
        let limbs = (bits / 64) as usize;
        let inner = (bits % 64) as u32;
        if self.0.iter().take(limbs).any(|&limb| limb != 0) {
            return false;
        }
        inner == 0
            || self
                .0
                .get(limbs)
                .is_none_or(|&limb| limb & ((1u64 << inner) - 1) == 0)
    }

    fn cmp(&self, other: &Big) -> Ordering {
        self.0
            .len()
            .cmp(&other.0.len())
            .then_with(|| self.0.iter().rev().cmp(other.0.iter().rev()))
    }

    fn add(&self, other: &Big) -> Big {
        let longest = self.0.len().max(other.0.len());
        let mut out = Vec::with_capacity(longest + 1);
        let mut carry = false;
        for index in 0..longest {
            let a = self.0.get(index).copied().unwrap_or(0);
            let b = other.0.get(index).copied().unwrap_or(0);
            let (partial, c1) = a.overflowing_add(b);
            let (total, c2) = partial.overflowing_add(u64::from(carry));
            out.push(total);
            carry = c1 || c2;
        }
        if carry {
            out.push(1);
        }
        Big(out).trim()
    }

    /// `self - other`; the caller guarantees `self >= other`.
    fn sub(&self, other: &Big) -> Big {
        let mut out = Vec::with_capacity(self.0.len());
        let mut borrow = false;
        for (index, &a) in self.0.iter().enumerate() {
            let b = other.0.get(index).copied().unwrap_or(0);
            let (partial, b1) = a.overflowing_sub(b);
            let (total, b2) = partial.overflowing_sub(u64::from(borrow));
            out.push(total);
            borrow = b1 || b2;
        }
        Big(out).trim()
    }

    fn mul(&self, other: &Big) -> Big {
        if self.is_zero() || other.is_zero() {
            return Big::zero();
        }
        let mut out = vec![0u64; self.0.len() + other.0.len()];
        for (i, &a) in self.0.iter().enumerate() {
            let mut carry = 0u128;
            for (j, &b) in other.0.iter().enumerate() {
                let slot = out.get(i + j).copied().unwrap_or(0);
                let cell = u128::from(a) * u128::from(b) + u128::from(slot) + carry;
                if let Some(target) = out.get_mut(i + j) {
                    *target = cell as u64;
                }
                carry = cell >> 64;
            }
            if let Some(target) = out.get_mut(i + other.0.len()) {
                *target = carry as u64;
            }
        }
        Big(out).trim()
    }

    fn mul_u64(&self, factor: u64) -> Big {
        self.mul(&Big::from_u64(factor))
    }

    /// Quotient and remainder of a division by a nonzero `u64`.
    fn divrem_u64(&self, divisor: u64) -> (Big, u64) {
        let mut out = vec![0u64; self.0.len()];
        let mut remainder = 0u128;
        for (index, &limb) in self.0.iter().enumerate().rev() {
            let cell = (remainder << 64) | u128::from(limb);
            if let Some(target) = out.get_mut(index) {
                *target = (cell / u128::from(divisor)) as u64;
            }
            remainder = cell % u128::from(divisor);
        }
        (Big(out).trim(), remainder as u64)
    }

    fn to_u128(&self) -> Option<u128> {
        match self.0.as_slice() {
            [] => Some(0),
            [low] => Some(u128::from(*low)),
            [low, high] => Some(u128::from(*low) | (u128::from(*high) << 64)),
            _ => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fsum_is_exact_where_a_plain_sum_is_not() {
        assert_eq!(fsum(&[0.1; 10]), Some(1.0));
        assert_eq!(fsum(&[1e100, 1.0, -1e100]), Some(1.0));
        assert_eq!(fsum(&[1e-16, 1.0, 1e16]), Some(1.000_000_000_000_000_2e16));
        assert_eq!(fsum(&[]), Some(0.0));
        assert_eq!(fsum(&[f64::NAN]), None);
        assert_eq!(
            fsum(&[f64::MAX, f64::MAX, -f64::MAX]),
            None,
            "intermediate overflow"
        );
    }

    #[test]
    fn fmean_divides_the_exact_sum() {
        assert_eq!(fmean(&[3.5, 4.0, 5.25]), Some(4.25));
        assert_eq!(fmean(&[]), None);
    }

    #[test]
    fn stdev_matches_pythons_docstring_and_edges() {
        assert_eq!(
            stdev(&[1.5, 2.5, 2.5, 2.75, 3.25, 4.75]),
            Some(1.081_087_415_521_982_7)
        );
        assert_eq!(stdev(&[2.0, 2.0, 2.0]), Some(0.0));
        assert_eq!(stdev(&[0.0, 0.0]), Some(0.0));
        assert_eq!(stdev(&[1.0]), None);
        assert_eq!(stdev(&[1.0, f64::INFINITY]), None);
        assert_eq!(stdev(&[1.0, 3.0]), Some(2.0_f64.sqrt()));
    }

    #[test]
    fn stdev_survives_a_huge_spread_and_subnormals() {
        assert_eq!(stdev(&[1e300, -1e300, 5e-324]), Some(1e300));
        // sd = 5e-324 / sqrt(2) = 3.5e-324: above half the smallest subnormal, so it rounds up to it
        assert_eq!(stdev(&[0.0, 5e-324]), Some(5e-324));
        assert_eq!(
            stdev(&[f64::MAX, -f64::MAX]),
            None,
            "the result does not fit a float"
        );
    }

    #[test]
    fn rounding_to_a_float_follows_ties_to_even() {
        assert_eq!(ldexp_rounded((1 << 53) + 1, 0), 9_007_199_254_740_992.0);
        assert_eq!(ldexp_rounded((1 << 53) + 3, 0), 9_007_199_254_740_996.0);
        assert_eq!(ldexp_rounded(1, -1074), 5e-324);
        assert_eq!(
            ldexp_rounded(3, -1075),
            1e-323,
            "1.5 units: the tie goes to the even 2"
        );
        assert_eq!(
            ldexp_rounded(1, -1075),
            0.0,
            "exactly half the smallest unit: ties to even, zero"
        );
        assert_eq!(ldexp_rounded(5, -1076), 5e-324, "1.25 units rounds down");
    }

    #[test]
    fn the_big_integer_agrees_with_u128_arithmetic() {
        let a = Big::from_u64(u64::MAX).shl(40);
        let b = Big::from_u64(0xdead_beef_cafe);
        let product = a.mul(&b);
        let (back, rest) = product.divrem_u64(0xdead_beef_cafe);
        assert_eq!((back, rest), (a.clone(), 0));
        assert_eq!(a.shr(40), Big::from_u64(u64::MAX));
        assert_eq!(a.add(&b).sub(&b), a);
        assert!(a.low_bits_zero(40) && !a.low_bits_zero(41));
        assert_eq!(a.bit_len(), 104);
    }
}
